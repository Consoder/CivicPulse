def test_ai_analysis_report_vote_status_and_delete():
    with TestClient(app) as client:
        response = client.post("/api/ai/analyze", json={
            "image_base64": "dGVzdA==", "image_mime_type": "image/jpeg",
            "location_lat": 26.9124, "location_lng": 75.7873,
            "location_address": "Jaipur",
        })
        assert response.status_code == 200, response.text
        assert response.json()["agent3_priority"]["priority_score"] >= 0
        created = client.post("/api/issues", json={
            "title": "Regression test streetlight issue",
            "description": "This issue was generated by an automated test.",
            "location": {"lat": 26.9124, "lng": 75.7873, "address": "Jaipur"},
            "cie_response": response.json(),
        })
        assert created.status_code == 201, created.text
        issue_id = created.json()["id"]
        assert client.get(f"/api/issues/{issue_id}").status_code == 200

        vote = {"issue_id": issue_id, "vote_type": "UPVOTE"}
        first = client.post("/api/votes", json=vote)
        repeated = client.post("/api/votes", json=vote)
        assert first.status_code == repeated.status_code == 200
        assert first.json()["upvotes"] == repeated.json()["upvotes"] == 1

        updated = client.patch(f"/api/issues/{issue_id}/status", json={"status": "IN_PROGRESS"})
        assert updated.status_code == 200
        assert updated.json()["status"] == "IN_PROGRESS"
        assert client.delete(f"/api/issues/{issue_id}").status_code == 200

        assert client.get(f"/api/issues/{issue_id}").status_code == 404
        listed = client.get("/api/issues")
        assert listed.status_code == 200
        assert not any(item["id"] == issue_id for item in listed.json()["items"])


